function makeCore(
  id: string,
  name: string,
  age: number,
  traits: {
    curiosity: number;
    assertiveness: number;
    independence: number;
    empathy: number;
    playfulness: number;
    openness: number;
    patience: number;
    confidence: number;
  },
  values: string[],
  preferences: string[],
  dislikes: string[],
  communicationStyle: CharacterCore["communicationStyle"],
): CharacterCore {
  return {
    ...defaultCharacter,
    id,
    name,
    age,
    adult: true,
    identityVersion: 1,
    immutableTraits: {
      curiosity: traits.curiosity,
      assertiveness: traits.assertiveness,
      independence: traits.independence,
      empathy: traits.empathy,
      playfulness: traits.playfulness,
    },
    slowTraits: {
      openness: traits.openness,
      patience: traits.patience,
      confidence: traits.confidence,
    },
    values,
    preferences,
    dislikes,
    preferenceRules: [],
    communicationStyle,
  };
}

